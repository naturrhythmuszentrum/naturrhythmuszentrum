//! Deterministic adjacent-transposition enumeration with unsealed finite evidence.

use super::action::{AT, invalid};
use crate::budget::{Budget, BudgetKind};
use crate::error::Fault;
use crate::graph::{Cas, Handle, State, size};
use crate::proof_model::{ApplicationDraft, Certificate, Statement};
use crate::solving::coefficients::storage::{copied, reserve, vector};
use crate::solving::symmetric::algebra::Polynomial;
use crate::solving::{
    CertificatePermutationOrbitCoverage, SolveCertificate, SolveSchema, SolveStatement,
    StatementOrbit,
};

/// A finite producer proposal; only the independent tag-14 checker can seal it.
#[derive(Debug)]
pub(crate) struct Orbit {
    /// First member is the starting seed; later members use deterministic breadth-first order.
    pub(crate) members: Vec<Polynomial>,
    /// All adjacent transpositions, so closure supplies full symmetric invariance.
    pub(crate) generators: Vec<Vec<u32>>,
    /// One row per member, one column per generator.
    pub(crate) actions: Vec<Vec<u32>>,
    /// A generator word from the seed to every retained member.
    pub(crate) words: Vec<Vec<u32>>,
}

/// `S_n` is generated by adjacent swaps, including the empty inventory for n at most one.
pub(crate) fn adjacent(degree: usize, budget: &mut Budget) -> Result<Vec<Vec<u32>>, Fault> {
    budget.check(BudgetKind::PolynomialVariables, size(degree, AT)?, AT)?;
    let mut result = vector(degree.saturating_sub(1), budget)?;
    for slot in 0..degree.saturating_sub(1) {
        let mut generator = vector(degree, budget)?;
        for position in 0..degree {
            generator.push(u32::try_from(position).map_err(|_| invalid())?);
        }
        generator.swap(slot, slot + 1);
        result.push(generator);
    }
    Ok(result)
}

/// Compare all retained normalized members before reserving a new orbit entry.
fn locate(
    orbit: &Orbit,
    image: &Polynomial,
    state: &State,
    budget: &mut Budget,
) -> Result<Option<usize>, Fault> {
    for (index, member) in orbit.members.iter().enumerate() {
        if member.equals(image, state, budget)? {
            return Ok(Some(index));
        }
    }
    Ok(None)
}

impl Orbit {
    /// Reserve an attempted new peak before copying its reaching word or retaining its polynomial.
    fn append(
        &mut self,
        image: Polynomial,
        source: usize,
        generator: usize,
        budget: &mut Budget,
    ) -> Result<usize, Fault> {
        let count = size(self.members.len(), AT)?
            .checked_add(1)
            .ok_or_else(|| Fault::capacity(BudgetKind::OrbitMembers, AT))?;
        budget.solving(BudgetKind::OrbitMembers, count, AT)?;
        let mut word = copied(self.words.get(source).ok_or_else(invalid)?, budget)?;
        reserve(&mut word, 1, budget)?;
        word.push(u32::try_from(generator).map_err(|_| invalid())?);
        reserve(&mut self.members, 1, budget)?;
        reserve(&mut self.words, 1, budget)?;
        let index = self.members.len();
        self.words.push(word);
        self.members.push(image);
        Ok(index)
    }

    /// Supply ordinary graph syntax and the exact statement the replay checker must reconstruct.
    pub(crate) fn application(
        &self,
        cas: &mut Cas,
        context: &Handle,
        budget: &mut Budget,
    ) -> Result<ApplicationDraft, Fault> {
        let seed = self.members.first().ok_or_else(invalid)?;
        let degree = u32::try_from(seed.variables.len()).map_err(|_| invalid())?;
        let mut members = vector(self.members.len(), budget)?;
        for member in &self.members {
            members.push(member.stage(cas, budget)?);
        }
        let seed = members.first().ok_or_else(invalid)?.clone();
        let data = CertificatePermutationOrbitCoverage {
            seed,
            degree,
            generators: rows(&self.generators, budget)?,
            members,
            actions: rows(&self.actions, budget)?,
            words: rows(&self.words, budget)?,
        };
        Ok(ApplicationDraft {
            rule: crate::rule::Primitive::Solve(SolveSchema::PermutationOrbitCoverage),
            context: context.clone(),
            conclusion: Statement::Solve(Box::new(SolveStatement::Orbit(StatementOrbit {
                seed: data.seed.clone(),
                generators: rows(&data.generators, budget)?,
                members: copied(&data.members, budget)?,
                actions: rows(&data.actions, budget)?,
            }))),
            premises: Vec::new(),
            substitutions: Vec::new(),
            certificate: Certificate::Solve(Box::new(SolveCertificate::PermutationOrbitCoverage(
                data,
            ))),
        })
    }
}

/// Copy nested bounded tables without an uncharged deep clone.
fn rows(source: &[Vec<u32>], budget: &mut Budget) -> Result<Vec<Vec<u32>>, Fault> {
    let mut result = vector(source.len(), budget)?;
    for row in source {
        result.push(copied(row, budget)?);
    }
    Ok(result)
}

/// Enumerate the complete finite orbit before deciding whether its degree is useful.
pub(crate) fn enumerate(
    seed: &Polynomial,
    state: &State,
    budget: &mut Budget,
) -> Result<Orbit, Fault> {
    budget.solving(BudgetKind::OrbitMembers, 1, AT)?;
    let mut members = vector(1, budget)?;
    budget.solving(BudgetKind::OrbitTerms, size(seed.form.terms.len(), AT)?, AT)?;
    members.push(seed.copy(state, budget)?);
    let mut words = vector(1, budget)?;
    words.push(Vec::new());
    let mut result = Orbit {
        members,
        generators: adjacent(seed.variables.len(), budget)?,
        actions: Vec::new(),
        words,
    };
    let mut cursor = 0;
    while cursor < result.members.len() {
        let mut row = vector(result.generators.len(), budget)?;
        for generator in 0..result.generators.len() {
            let image = result.members.get(cursor).ok_or_else(invalid)?.permute(
                result.generators.get(generator).ok_or_else(invalid)?,
                state,
                budget,
            )?;
            let target = match locate(&result, &image, state, budget)? {
                Some(index) => index,
                None => result.append(image, cursor, generator, budget)?,
            };
            row.push(u32::try_from(target).map_err(|_| invalid())?);
        }
        reserve(&mut result.actions, 1, budget)?;
        result.actions.push(row);
        cursor += 1;
    }
    Ok(result)
}
