//! Deterministic reviewed catalogues and recorded server observations.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use serde_json::Value;

use crate::{Error, envelope};

mod record;
mod validate;

/// The engineering input follows the authored layout (´rule:docgen:input-layout´).
/// ´const:docgen:engineering-input´ (´[ORCHESTRATION-alg:const:text]´)
/// ´const:docgen:engineering-input-text-x53f51087´
pub(crate) const INPUT: &str = "data/inputs/engineering.toml";
/// The engineering dataset is a distinct generated artifact (´rule:docgen:dataset-identities´).
/// ´const:docgen:engineering-dataset´ (´[ORCHESTRATION-alg:const:text]´)
/// ´const:docgen:engineering-dataset-text-xeebb058d´
pub(crate) const DATASET: &str = "data/datasets/engineering.json";
/// The input namespace distinguishes reviewed records from generated bytes (´rule:docgen:dataset-identities´).
/// ´const:docgen:engineering-input-namespace´ (´[ORCHESTRATION-alg:const:text]´)
/// ´const:docgen:engineering-input-namespace-text-xc0f84976´
const INPUT_NAMESPACE: &str = "org.naturrhythmuszentrum.docs.input.engineering";
/// The dataset namespace identifies engineering table payloads (´rule:docgen:dataset-identities´).
/// ´const:docgen:engineering-dataset-namespace´ (´[ORCHESTRATION-alg:const:text]´)
/// ´const:docgen:engineering-dataset-namespace-text-xe5c6235e´
const DATASET_NAMESPACE: &str = "org.naturrhythmuszentrum.docs.dataset.engineering";

/// Read, validate and canonicalize records without executing workspace code.
pub(crate) fn derive(root: &Path, owners: &BTreeSet<String>) -> Result<(Vec<u8>, Value), Error> {
    let value = envelope::read_toml(root, INPUT)?;
    envelope::validate(&value, INPUT, INPUT_NAMESPACE, owners)?;
    let object = value
        .as_object()
        .ok_or_else(|| invalid("input must be an object"))?;
    let sources = envelope::string_array(object, INPUT, "sources")?;
    let labels = envelope::string_array(object, INPUT, "labels")?;
    let root_owner = value.get("owner").and_then(Value::as_str) == Some("NRZ");
    if !root_owner || !sources.is_empty() || !labels.is_empty() {
        return Err(invalid(
            "input requires root ownership and empty sources and labels",
        ));
    }
    let mut records: record::Records = serde_json::from_value(envelope::payload(&value, INPUT)?)
        .map_err(|error| invalid(&error.to_string()))?;
    validate::records(root, &mut records)?;
    encode(&records)
}

/// Encode reviewed records and their complete source set.
fn encode(records: &record::Records) -> Result<(Vec<u8>, Value), Error> {
    let value = serde_json::to_value(records).map_err(|error| invalid(&error.to_string()))?;
    let fields: BTreeMap<String, Value> = value
        .as_object()
        .ok_or_else(|| invalid("engineering payload must be an object"))?
        .iter()
        .map(|(key, value)| (key.clone(), value.clone()))
        .collect();
    let sources = std::iter::once(INPUT.to_owned())
        .chain(
            records
                .source_versions
                .iter()
                .map(|source| source.path.clone()),
        )
        .collect::<Vec<_>>();
    let bytes = envelope::encode(DATASET, DATASET_NAMESPACE, "NRZ", &sources, &[], &fields)?;
    let value = serde_json::from_slice(&bytes).map_err(|error| invalid(&error.to_string()))?;
    Ok((bytes, value))
}

/// Rendering rechecks source currency and all rows instead of trusting stored payloads.
pub(crate) fn validate_dataset(
    root: &Path,
    value: &Value,
    owners: &BTreeSet<String>,
) -> Result<(), Error> {
    envelope::validate(value, DATASET, DATASET_NAMESPACE, owners)?;
    let (_, expected) = derive(root, owners)?;
    if value != &expected {
        return Err(invalid(
            "committed engineering dataset differs from reviewed inputs",
        ));
    }
    Ok(())
}

/// Retain the specific failed input rule as a path-bearing value.
fn invalid(detail: &str) -> Error {
    Error::Payload {
        path: INPUT.to_owned(),
        detail: detail.to_owned(),
    }
}

